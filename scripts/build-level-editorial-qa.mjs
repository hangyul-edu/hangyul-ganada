#!/usr/bin/env node
/**
 * Renders docs/VOCABULARY_LEVEL_EDITORIAL_QA.md — the level ladder as a
 * document a person reads, because a distribution table cannot say whether a
 * level-12 word belongs at level 12.
 *
 * For every level: the count, the 25 easiest and 25 hardest by the model's
 * own difficulty score, and up to 100 representative words (deterministic
 * stride sample). The "moved this pass" and "suspicious" sections are
 * editorial and live in content/vocabulary/level-editorial-notes.json — this
 * script renders them; a person writes them.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(ROOT, p), 'utf8'));
const v = read('apps/web/src/data/generated/vocabulary.json');
const en = read('apps/web/src/data/generated/vocabulary.en.json').words;
const notes = existsSync(join(ROOT, 'content/vocabulary/level-editorial-notes.json'))
  ? read('content/vocabulary/level-editorial-notes.json') : { moved: {}, suspicious: {} };
const rows = v.words.map((w, i) => ({ w: w.word, g: en[i][0], s: w.difficulty_score, level: w.level }));
const byLevel = new Map();
for (const r of rows) { (byLevel.get(r.level) ?? byLevel.set(r.level, []).get(r.level)).push(r); }
let out = `# Vocabulary level editorial QA\n\nGenerated by \`scripts/build-level-editorial-qa.mjs\` from the shipping corpus
(${rows.length} words). The counts and samples are mechanical; the *moved* and
*suspicious* sections are a person's judgement, recorded in
\`content/vocabulary/level-editorial-notes.json\`. Read the samples — a
distribution cannot tell a mis-shelved word from a fine one.\n`;
const fmt = (r) => `${r.w} (${r.g})`;
for (let level = 1; level <= 30; level += 1) {
  const words = (byLevel.get(level) ?? []).sort((a, b) => a.s - b.s);
  out += `\n## Level ${level} — ${words.length} words\n\n`;
  out += `**Easiest 25 by score:** ${words.slice(0, 25).map(fmt).join(' · ')}\n\n`;
  out += `**Hardest 25 by score:** ${words.slice(-25).map(fmt).join(' · ')}\n\n`;
  const stride = Math.max(1, Math.floor(words.length / 100));
  const rep = words.filter((_, i) => i % stride === 0).slice(0, 100);
  out += `**Representative ${rep.length}:** ${rep.map((r) => r.w).join(' · ')}\n`;
  const moved = notes.moved[String(level)] ?? [];
  const susp = notes.suspicious[String(level)] ?? [];
  if (moved.length) out += `\n**Moved this pass:** ${moved.map((m) => `${m.word} — ${m.why}`).join(' ; ')}\n`;
  if (susp.length) out += `\n**Suspicious, read and adjudicated:** ${susp.map((m) => `${m.word} — ${m.verdict}`).join(' ; ')}\n`;
}
writeFileSync(join(ROOT, 'docs/VOCABULARY_LEVEL_EDITORIAL_QA.md'), out);
console.log(`wrote docs/VOCABULARY_LEVEL_EDITORIAL_QA.md (${rows.length} words, 30 levels)`);
