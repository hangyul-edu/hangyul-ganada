#!/usr/bin/env node
/**
 * The editorial ledger: every learner-facing Korean string, and who read it.
 *
 *   npm run copy:ledger            record the current strings as read
 *   npm run copy:ledger:check      fail on any string no reading covers
 *
 * ## Why a ledger and not another rule
 *
 * The copy gates in this repo look for *shapes*: a banned term, a register
 * mismatch, a placeholder that went missing. They are worth having and they
 * cannot see the thing that matters most — whether a sentence sounds like a
 * person wrote it. "숫자가 두 벌 있어요" passed every automated check in this
 * repository for two releases.
 *
 * So the check here is not on the Korean. It is on the *reading*: each string
 * is recorded with a hash of its current text, and a string whose text has
 * changed since it was last read is a finding. That makes the audit a thing
 * with a state rather than an event, and it makes the cost of adding a
 * learner-facing sentence include the cost of somebody reading it.
 *
 * ## What a row means
 *
 * `kept` — read, in the rendered screen, and left alone.
 * `rewritten` — read, found wanting, and replaced; `why` names the fault.
 *
 * `why` is required on a rewrite and forbidden on a keep, because a reason
 * written against every string is a reason nobody reads.
 *
 * ## What this deliberately does not claim
 *
 * Not a native review. Every row here was read by the model that wrote the
 * sentence, which is the same pair of eyes twice, and the report says so where
 * it lists the external blockers. The ledger records that a reading happened
 * and what it decided; it does not upgrade who did it.
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const KO = join(root, 'apps/web/src/locales/ko');
const LEDGER = join(root, 'docs/copy-audit-ko.json');
const CHECK = process.argv.includes('--check');

/** `namespace:dotted.path` → the Korean a learner reads. */
function strings() {
  const out = new Map();
  for (const file of readdirSync(KO).filter((name) => name.endsWith('.json'))) {
    const namespace = file.replace(/\.json$/, '');
    const walk = (node, path) => {
      if (typeof node === 'string') {
        out.set(`${namespace}:${path}`, node);
        return;
      }
      if (Array.isArray(node)) {
        node.forEach((value, index) => walk(value, `${path}[${index}]`));
        return;
      }
      if (node && typeof node === 'object') {
        for (const [key, value] of Object.entries(node)) walk(value, path ? `${path}.${key}` : key);
      }
    };
    walk(JSON.parse(readFileSync(join(KO, file), 'utf8')), '');
  }
  return out;
}

const digest = (text) => createHash('sha256').update(text).digest('hex').slice(0, 12);

const current = strings();
const ledger = existsSync(LEDGER) ? JSON.parse(readFileSync(LEDGER, 'utf8')) : { _comment: '', read: {} };

const unread = [];
const changed = [];
const orphaned = [];

for (const [key, text] of current) {
  const row = ledger.read[key];
  if (!row) unread.push(key);
  else if (row.hash !== digest(text)) changed.push(key);
}
for (const key of Object.keys(ledger.read)) if (!current.has(key)) orphaned.push(key);

if (!CHECK) {
  /*
   * Recording is deliberately not the same as reading.
   *
   * This marks every string as `kept` unless the ledger already says otherwise,
   * which is only honest because the run that adds a row is the run in which
   * somebody has just read the batch. A row promoted to `rewritten` keeps its
   * reason.
   */
  const next = { ...ledger.read };
  for (const [key, text] of current) {
    const previous = next[key];
    next[key] = {
      hash: digest(text),
      decision: previous?.decision === 'rewritten' && previous.hash === digest(text) ? 'rewritten' : 'kept',
      ...(previous?.why && previous.hash === digest(text) ? { why: previous.why } : {}),
    };
  }
  for (const key of orphaned) delete next[key];
  writeFileSync(
    LEDGER,
    `${JSON.stringify(
      {
        _comment:
          'Every learner-facing Korean string, with a hash of the text that was read. ' +
          'A string whose hash no longer matches has changed since its last reading and must be read again. ' +
          'Generated by scripts/build-copy-ledger.mjs; the decisions are written by the person reading.',
        strings: current.size,
        read: next,
      },
      null,
      1,
    )}\n`,
  );
  console.log(`Copy ledger — ${current.size} Korean strings recorded as read`);
  if (orphaned.length) console.log(`  dropped ${orphaned.length} row(s) for strings that no longer exist`);
  process.exit(0);
}

const rewritten = Object.values(ledger.read).filter((row) => row.decision === 'rewritten');
console.log(`Copy ledger — ${current.size} learner-facing Korean strings`);
console.log(`  ${Object.keys(ledger.read).length} carry a reading; ${rewritten.length} were rewritten because of one`);

const problems = [
  ...unread.map((key) => `${key}: no reading recorded — read it, then run npm run copy:ledger`),
  ...changed.map((key) => `${key}: changed since it was last read`),
  ...orphaned.map((key) => `${key}: recorded as read, but no longer exists`),
];
if (problems.length === 0) {
  console.log('  every Korean string a learner can see has been read at its current wording.');
} else {
  console.log(`\n  ${problems.length} problem(s):`);
  for (const problem of problems.slice(0, 30)) console.log(`    ${problem}`);
  if (problems.length > 30) console.log(`    …and ${problems.length - 30} more`);
  process.exit(1);
}
