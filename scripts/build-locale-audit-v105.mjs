#!/usr/bin/env node
/**
 * docs/LOCALE_AUDIT_v1.0.5.md — one row per interface language: what was
 * reviewed, what was corrected, what is still waiting for a person.
 *
 *   node scripts/build-locale-audit-v105.mjs           write
 *   node scripts/build-locale-audit-v105.mjs --check   fail when stale
 *
 * Inputs, all of them generated or diff-derived — nothing in the table is typed in:
 *
 *   docs/locale-audit-v105-input.json      the correction tallies of this remediation (provenance inside)
 *   docs/content-translation-audit.json    rows audited, blocking findings, shared meanings, per locale
 *   docs/quote-translation-audit.json      the two quotations, per locale, with the human-review flags
 *   docs/locale-audit-v105-layout.json     what qa:locales measured, per locale (written by scripts/qa-locale-screens.mjs --summary)
 *   apps/web/src/locales/<loc>/*.json      the interface strings, counted
 *
 * The review status column uses the ledger vocabulary only. Every locale is
 * HUMAN REVIEW REQUIRED because no native speaker has read any of them; a
 * locale with an automated blocking finding would be OPEN, and none is.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const CHECK = process.argv.includes('--check');
const OUT = join(root, 'docs/LOCALE_AUDIT_v1.0.5.md');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));

const IN = read('docs/locale-audit-v105-input.json');
const T = read('docs/content-translation-audit.json');
const Q = read('docs/quote-translation-audit.json');
const LAYOUT = existsSync(join(root, 'docs/locale-audit-v105-layout.json')) ? read('docs/locale-audit-v105-layout.json') : null;

const locales = readdirSync(join(root, 'apps/web/src/locales'), { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

const flat = (o, p = '') => Object.entries(o).flatMap(([k, v]) => (v && typeof v === 'object' ? flat(v, `${p}${k}.`) : [[`${p}${k}`, v]]));
const uiCount = (loc) =>
  readdirSync(join(root, 'apps/web/src/locales', loc))
    .filter((f) => f.endsWith('.json'))
    .reduce((n, f) => n + flat(read(`apps/web/src/locales/${loc}/${f}`)).length, 0);

const n = (x) => x.toLocaleString('en-US');
const L = [];
L.push('# Per-locale content audit — web v1.0.5');
L.push('');
L.push(`GENERATED by \`scripts/build-locale-audit-v105.mjs\` on ${IN.date} from the inputs named in the script. One row per interface language. Every learner-facing field a locale carries was passed through the automated gates in a separate pass per field type (interface strings → \`i18n:check\`, \`locale:content:check\`, \`copy:audit:check\`; word meanings and example translations → \`translation:audit:check\`, \`vocabulary:translation:check\`, \`translation:semantics:check\`; exercise prompts → \`copy:generated:check\`, \`leveltest:locale:check\`; quotations → \`quotes:qa:check\`, \`quotes:render:check\`; child safety → \`content:safety:check\` with the locale's runtime supplement; layout → \`qa:locales:check\`, \`screens:audit:check\`), and a model read the sampled rows recorded in \`docs/content-translation-review-sample.json\` and \`docs/QUOTE_TRANSLATION_REVIEW_v1.0.5.md\`. **No row is NATIVE-SPEAKER REVIEWED**: no native speaker has read any locale, and the last column says so for every one.`);
L.push('');
L.push('## How the counts were made');
L.push('');
L.push(`* **Vocabulary meanings / examples corrected** — words whose meaning or example translation in that locale changed during this remediation: the copy packs and entry files diffed against commit \`${IN.baseline}\` for words that existed there, against the \`${IN.backup}\` working-tree backup for words added in this remediation, and the remediation patch files applied before that backup. The word lists are in \`docs/locale-audit-v105-input.json\`.`);
L.push('* **UI strings corrected** — interface strings whose text changed against the same commit. "Interface keys" counts every key in the locale\'s JSON files, plural forms separately, which is why it is larger than the 894 English strings the locale ledger counts.');
L.push('* **Exercise collisions corrected** — groups of taught words that shared one gloss and were differentiated so they can be distractors for each other. Only the English gloss was rewritten (it is the gloss every other pack was translated from); in the other 31 locales a shared meaning is not corrected but *rejected*: `collideInAnyLocale` refuses the pair as a distractor at build time, and the count of such groups is shown so the size of that reliance is visible.');
L.push('* **Safety findings corrected** — strings the child-safe policy or its runtime supplement refused and that were rewritten.');
L.push('* **Long-text layout findings corrected** — what `qa:locales` measured on the rendered screens (overflow, sideways scroll, untranslated, empty names, overlap) at the end of the remediation; a locale with nothing measured wrong reads 0 / 0 (found / corrected).');
L.push('* **Remaining human-review items** — what only a native speaker can settle: the whole word pack and interface, always, plus the quotation rows the model flagged.');
L.push('');
L.push('## The table');
L.push('');
L.push('| Locale | Fields reviewed | Vocabulary meanings corrected | Examples corrected | UI strings corrected | Exercise collisions corrected | Safety findings corrected | Long-text layout findings corrected | Remaining human-review items | Review status |');
L.push('|:---|:---|---:|---:|---:|:---|---:|:---|:---|:---|');
const totals = { meanings: 0, examples: 0, ui: 0, safety: 0, layoutFound: 0 };
for (const loc of locales) {
  const c = IN.corrections[loc] ?? { meanings: 0, examples: 0 };
  const per = T.per_locale[loc];
  const ui = uiCount(loc);
  const uiFix = (IN.uiStrings[loc] ?? []).length;
  const safety = (IN.safety[loc] ?? []).length;
  const quotesHuman = Object.values(Q.quotes).filter((q) => q[loc]?.status === 'NATIVE-SPEAKER REVIEW REQUIRED').length;
  const fields = `${n(ui)} interface keys; ${n(per.meanings)} word meanings; ${n(per.examples)} example translations; 2 quotations; exercise prompts (${loc === 'en' || loc === 'ko' ? 'inline' : 'generated'}); ${per.notes ? `${n(per.notes)} notes; ` : ''}child-safety runtime supplement`;
  const collisions =
    loc === 'en'
      ? `${IN.collisionsCorrected.en.sharedGlossGroupsBefore} shared-gloss groups → ${IN.collisionsCorrected.en.sharedGlossGroupsAfter}`
      : loc === 'ko'
        ? '0 corrected (Korean is the headword side; 0 duplicate headwords)'
        : IN.collisionsRejectedAtBuild[loc]
          ? `0 corrected; ${n(IN.collisionsRejectedAtBuild[loc].sameMeaningGroups)} same-meaning groups rejected as distractor pairs at build`
          : `0 corrected; ${n(per.sharedMeanings ?? 0)} same-meaning groups rejected at build`;
  const lay = LAYOUT?.locales?.[loc];
  const layout = lay ? `${lay.found} found / ${lay.corrected} corrected (${lay.screens} screens)` : 'not measured';
  if (lay) totals.layoutFound += lay.found;
  const remaining = [
    `native read of ${n(per.meanings)} meanings + ${n(per.examples)} examples`,
    `native read of ${n(ui)} interface keys`,
    quotesHuman ? `${quotesHuman} quotation row${quotesHuman > 1 ? 's' : ''} flagged by the model` : 'quotation rows: none flagged',
  ].join('; ');
  const status = per.findings && (per.byCode ? Object.keys(per.byCode).some((k) => T.blocking_codes.includes(k)) : false) ? 'OPEN' : 'HUMAN REVIEW REQUIRED';
  totals.meanings += c.meanings; totals.examples += c.examples; totals.ui += uiFix; totals.safety += safety;
  L.push(`| ${loc} | ${fields} | ${c.meanings} | ${c.examples} | ${uiFix} | ${collisions} | ${safety} | ${layout} | ${remaining} | ${status} |`);
}
L.push('');
L.push(`Totals across the 32 locales: ${n(totals.meanings)} meaning corrections, ${n(totals.examples)} example corrections, ${totals.ui} interface-string corrections, ${totals.safety} safety rewrites${LAYOUT ? `, ${totals.layoutFound} layout findings` : ''}. The English column is large because English is the gloss every other pack was translated from, and its 108 shared glosses were rewritten one by one; the other locales' example counts are mostly the ${IN.corrections.ar?.examples ?? 0} Korean sentences that were replaced and therefore re-translated everywhere.`);
L.push('');
L.push('## The individual corrections that are not word counts');
L.push('');
for (const [loc, items] of Object.entries(IN.safety)) for (const item of items) L.push(`* **${loc}** (safety) — ${item}`);
for (const [loc, items] of Object.entries(IN.uiStrings)) for (const item of items) L.push(`* **${loc}** (interface) — ${item}`);
L.push('');
L.push('## What this document does not claim');
L.push('');
L.push('The counts say what changed and what was measured; they do not say the translations are natural. The automated translation audit finds missing, copied, placeholder and wrong-script rows and length outliers, and `docs/content-translation-review-sample.json` records what the model read; both are AUTOMATED CHECKED or MODEL-REVIEWED. The same-meaning group counts show how much the exercises rely on build-time rejection rather than on distinct translations, and a native reviewer would reduce them; that work is listed under external blockers in `docs/report.md`.');
L.push('');
const md = L.join('\n');
if (CHECK) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== md) { console.error(`${OUT} is stale — run node scripts/build-locale-audit-v105.mjs`); process.exit(1); }
  console.log('locale audit current');
} else {
  writeFileSync(OUT, md);
  console.log(`wrote ${OUT}: ${locales.length} locales`);
}
