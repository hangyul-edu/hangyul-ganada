#!/usr/bin/env node
/**
 * Whether the translated example sentences still translate the Korean ones.
 *
 *   node scripts/check-copy-freshness.mjs           rewrite the record
 *   node scripts/check-copy-freshness.mjs --check   fail if a pack has drifted
 *
 * ## The defect this was written for
 *
 * Twenty-four words had their example sentence rewritten to remove an
 * ambiguity — `일곱 시에 일어나요` became `알람 소리에 침대에서 일어났어요`, and
 * so on. The seven translations carried inside the editorial entry were updated
 * with them, because they live in the same row. The other twenty-four languages
 * live in `content/vocabulary/copy/<locale>.json`, keyed by word id, and they
 * were not: every one of them went on saying *I get up at seven* under a Korean
 * sentence about an alarm and a bed.
 *
 * Five gates read those files that day — `vocabulary:translation`,
 * `translation:semantics`, `locale:content`, `locale:editorial`,
 * `copy:generated` — and all five passed. None of them compares a translated
 * example to the Korean example: they check key parity, gloss agreement and
 * placeholder shape, which is one level away from the thing that was wrong.
 *
 * ## What this records
 *
 * `content/vocabulary/copy-examples.json` — the Korean sentence each pack's
 * translations were written against, one line per word. The check compares it
 * to the live pack. Editing an example without redoing the translations moves
 * the pack and not the record, and the check fails.
 *
 * ## What it cannot tell you
 *
 * Whether a translation is *right*. Rewriting the record is one command, and a
 * person who runs it without translating anything gets a green build and a
 * wrong sentence. It closes the gap where the change is silent, not the one
 * where it is deliberate and careless. Reading remains a person's job — see
 * `docs/AMBIGUITY_LEDGER.md`.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const COPY = join(ROOT, 'content', 'vocabulary', 'copy');
/* Beside the copy directory, not inside it: `build_vocabulary.py` reads every
   *.json in there and expects each to declare a `locale`. */
const RECORD = join(ROOT, 'content', 'vocabulary', 'copy-examples.json');
const CHECK = process.argv.includes('--check');

const vocabulary = JSON.parse(
  readFileSync(join(ROOT, 'apps', 'web', 'src', 'data', 'generated', 'vocabulary.json'), 'utf8'),
);
const exampleOf = new Map(vocabulary.words.map((word) => [word.id, word.example ?? '']));

const locales = readdirSync(COPY)
  .filter((name) => name.endsWith('.json') && !name.startsWith('_'))
  .map((name) => name.slice(0, -5))
  .sort();

/** Every word id that any pack carries an example translation for. */
const translated = new Set();
const packs = new Map();
for (const locale of locales) {
  const words = JSON.parse(readFileSync(join(COPY, `${locale}.json`), 'utf8')).words;
  packs.set(locale, words);
  for (const [id, row] of Object.entries(words)) {
    if (Array.isArray(row) && row.length > 1 && row[1]) translated.add(id);
  }
}

const current = {};
for (const id of [...translated].sort()) {
  const example = exampleOf.get(id);
  if (example) current[id] = example;
}

const text = `${JSON.stringify(
  {
    _comment:
      'GENERATED by scripts/check-copy-freshness.mjs. The Korean example sentence that each ' +
      'locale pack’s example translation was written against. Rewriting an example without ' +
      'redoing content/vocabulary/copy/<locale>.json moves the pack and not this file, and ' +
      '`npm run copy:fresh:check` fails. Run `npm run copy:fresh` only after the translations ' +
      'have actually been redone.',
    examples: current,
  },
  null,
  2,
)}\n`;

if (!CHECK) {
  writeFileSync(RECORD, text);
  console.log(`recorded ${Object.keys(current).length} example sentences for ${locales.length} locales`);
  process.exit(0);
}

let recorded;
try {
  recorded = JSON.parse(readFileSync(RECORD, 'utf8')).examples;
} catch {
  console.error(`${RECORD} is missing — run \`npm run copy:fresh\``);
  process.exit(1);
}

const drifted = [];
const missing = [];
for (const id of Object.keys(current)) {
  if (!(id in recorded)) {
    missing.push(id);
  } else if (recorded[id] !== current[id]) {
    drifted.push({ id, was: recorded[id], now: current[id] });
  }
}
const orphaned = Object.keys(recorded).filter((id) => !(id in current));

console.log(
  `Translated example sentences — ${Object.keys(current).length} words × ${locales.length} locales\n`,
);
if (drifted.length === 0 && missing.length === 0 && orphaned.length === 0) {
  console.log('  every pack was written against the Korean sentence the corpus still carries.');
  process.exit(0);
}
for (const entry of drifted) {
  console.error(`  DRIFTED  ${entry.id}`);
  console.error(`      translated from: ${entry.was}`);
  console.error(`      corpus now says: ${entry.now}`);
  console.error(`      ${locales.length} locale pack(s) need their second row rewritten`);
}
for (const id of missing) console.error(`  UNRECORDED  ${id} — translated, but not in the record`);
for (const id of orphaned) console.error(`  ORPHANED    ${id} — recorded, but no longer translated`);
console.error(
  `\n${drifted.length + missing.length + orphaned.length} problem(s). ` +
    'Redo the translations, then run `npm run copy:fresh`.',
);
process.exit(1);
