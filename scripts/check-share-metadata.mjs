#!/usr/bin/env node
/**
 * The two things a shared link has to get right, checked against the built app.
 *
 *   npm run share:check
 *
 * ## What this is for
 *
 * Hangyul ganada is meant to be **shared and not indexed**. Those pull in
 * opposite directions and both are one edit away from breaking silently:
 *
 * * A link pasted into a message must render a card — title, one sentence, the
 *   brand image. That is Open Graph and it is read out of `index.html` by a
 *   crawler that never runs React, so it has to be correct in the *file*, not
 *   in a `useEffect`.
 * * The same URL must not appear in a search result. That is `noindex`, and it
 *   only works if the crawler is allowed to fetch the page and read it. A
 *   `Disallow: /` in `robots.txt` would keep the URL in the index rather than
 *   removing it — the failure this check exists to make impossible.
 *
 * Neither is visible in the app, neither is exercised by any other test, and
 * both are the kind of thing that gets noticed months later by somebody
 * wondering why the preview is blank.
 *
 * ## Why it reads `dist` rather than the source
 *
 * `index.html` is copied and rewritten by Vite, `public/` is copied wholesale,
 * and the image is generated by a Python script in a different workspace. The
 * question worth answering is not "is the tag in the source" but "is the tag,
 * and the file it points at, in the thing that gets uploaded". So this parses
 * the built `index.html`, resolves the image inside `dist`, and reads its real
 * pixel dimensions back out of the JPEG header.
 */

import { readFileSync, existsSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const DIST = join(root, 'apps', 'web', 'dist');

/** The public origin every absolute tag has to agree on. */
const ORIGIN = 'https://ganada.talkhangyul.com';

/** Every directive that has to appear in both robots meta tags and the header. */
const NOINDEX = ['noindex', 'nofollow', 'noarchive', 'nosnippet', 'noimageindex'];

const problems = [];
const notes = [];
const fail = (what) => problems.push(what);

if (!existsSync(join(DIST, 'index.html'))) {
  console.error('No build to check. Run `npm run build` first.');
  process.exit(1);
}

const html = readFileSync(join(DIST, 'index.html'), 'utf8');

/**
 * The document with every comment removed.
 *
 * Everything below is asked of *this* rather than of the raw file, because a
 * tag inside a comment is not a tag. That is not hypothetical: writing a
 * literal closing head tag inside one of the explanatory comments in
 * `index.html` made Vite inject the module bootstrap at that point — the first
 * match it found — which put the `<script src="/assets/index-….js">` *inside
 * the comment*. The build succeeded, every other gate passed, the page served
 * 200 with a correct title, and the app never mounted: `#root` was empty and
 * the console was silent. Only the end-to-end suite noticed, and only because
 * it looks at the rendered page.
 */
const visible = html.replace(/<!--[\s\S]*?-->/g, '');

/**
 * The content of `<meta name=…>` or `<meta property=…>`, decoded, or null.
 *
 * The attribute is matched against its *own* delimiter rather than against
 * `["']` as a character class. `Start Korean from zero… what you're likely to
 * forget` is delimited by double quotes and contains a single one, and a class
 * that excludes both stops at the apostrophe — which silently truncates the
 * description to 72 characters and makes the length assertion below test a
 * string nobody will ever see.
 */
function meta(kind, key) {
  const pattern = new RegExp(
    `<meta[^>]*\\b${kind}=(["'])${key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\1[^>]*>`,
    'i',
  );
  const tag = pattern.exec(visible)?.[0];
  if (!tag) return null;
  const content = /\bcontent=(["'])([\s\S]*?)\1/i.exec(tag)?.[2];
  return content == null ? null : decode(content);
}

/**
 * HTML entities back to the characters a reader sees.
 *
 * The tags are authored as markup, so `&` is `&amp;` in the file — and a
 * preview card shows `&`. Length limits and "does it name the product" are
 * questions about the decoded string.
 */
function decode(text) {
  return text
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#0?39;|&apos;/g, "'")
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&');
}

const named = (key) => meta('name', key);
const property = (key) => meta('property', key);

// --- 1. It says what the product is ----------------------------------------

const title = decode(/<title>([^<]*)<\/title>/i.exec(visible)?.[1] ?? '');
if (!title) fail('no <title> in the built index.html');
if (title && !/hangyul ganada/i.test(title)) fail(`<title> does not name the product: ${title}`);
if (title.length > 70) fail(`<title> is ${title.length} chars; a card truncates around 70`);

const description = named('description');
if (!description) fail('no meta description');
else if (description.length < 60) fail(`meta description is only ${description.length} chars`);
else if (description.length > 200) {
  fail(`meta description is ${description.length} chars; most surfaces cut near 160`);
}

/*
 * The app has to actually boot.
 *
 * One assertion, and the most important one in this file. See the note on
 * `visible`: the bootstrap script can end up commented out by an edit to the
 * prose *around* it, and nothing else in the repository notices.
 */
const bootstrap = /<script[^>]*\btype=(["'])module\1[^>]*\bsrc=(["'])([^"']+)\2[^>]*>/i.exec(
  visible,
);
if (!bootstrap) {
  fail(
    'no <script type="module"> outside a comment — the app will serve a blank page. ' +
      'Check index.html for a literal closing head tag inside a comment.',
  );
} else if (!existsSync(join(DIST, bootstrap[3]))) {
  fail(`the module bootstrap points at ${bootstrap[3]}, which is not in the build`);
} else {
  notes.push(`module bootstrap ${bootstrap[3]} is present and outside any comment`);
}

// --- 2. Open Graph, complete and absolute ----------------------------------

const og = {
  'og:type': property('og:type'),
  'og:site_name': property('og:site_name'),
  'og:url': property('og:url'),
  'og:title': property('og:title'),
  'og:description': property('og:description'),
  'og:image': property('og:image'),
  'og:image:secure_url': property('og:image:secure_url'),
  'og:image:type': property('og:image:type'),
  'og:image:alt': property('og:image:alt'),
  'og:image:width': property('og:image:width'),
  'og:image:height': property('og:image:height'),
};
for (const [key, value] of Object.entries(og)) {
  if (!value) fail(`missing ${key}`);
}
if (og['og:type'] && og['og:type'] !== 'website') fail(`og:type is ${og['og:type']}, expected website`);
for (const key of ['og:url', 'og:image', 'og:image:secure_url']) {
  const value = og[key];
  if (value && !value.startsWith(ORIGIN)) {
    fail(`${key} is not an absolute ${ORIGIN} URL: ${value}`);
  }
}
if (
  og['og:image'] &&
  og['og:image:secure_url'] &&
  og['og:image'] !== og['og:image:secure_url']
) {
  fail(`og:image and og:image:secure_url disagree: ${og['og:image']} vs ${og['og:image:secure_url']}`);
}

/*
 * Nothing a crawler must not see. `startsWith(ORIGIN)` above already refuses a
 * relative path or a foreign host, but a URL can start with the origin and
 * still smuggle a development value in later edits of this file — so the
 * poison list is checked against every image URL explicitly, including
 * twitter:image, which the origin rule below does not cover.
 */
const POISON = ['localhost', '127.0.0.1', 'file://', '/root/', 'vercel.app', '192.168.'];
for (const [key, value] of [
  ['og:image', og['og:image']],
  ['og:image:secure_url', og['og:image:secure_url']],
  ['og:url', og['og:url']],
]) {
  if (!value) continue;
  for (const marker of POISON) {
    if (value.includes(marker)) fail(`${key} contains a development value: ${value}`);
  }
}

// --- 3. Twitter / X --------------------------------------------------------

const twitter = {
  'twitter:card': named('twitter:card'),
  'twitter:title': named('twitter:title'),
  'twitter:description': named('twitter:description'),
  'twitter:image': named('twitter:image'),
};
for (const [key, value] of Object.entries(twitter)) {
  if (!value) fail(`missing ${key}`);
}
if (twitter['twitter:card'] && twitter['twitter:card'] !== 'summary_large_image') {
  fail(`twitter:card is ${twitter['twitter:card']}, expected summary_large_image`);
}
if (twitter['twitter:image'] && !twitter['twitter:image'].startsWith(ORIGIN)) {
  fail(`twitter:image is not an absolute ${ORIGIN} URL: ${twitter['twitter:image']}`);
}
if (
  twitter['twitter:image'] &&
  og['og:image'] &&
  twitter['twitter:image'] !== og['og:image']
) {
  // One artwork by design: the same key visual on every platform. A deliberate
  // second artwork would relax this line, with the reason written beside it.
  fail(`twitter:image and og:image disagree: ${twitter['twitter:image']} vs ${og['og:image']}`);
}

// --- 4. The image is really there, and is really that size -----------------

if (og['og:image']) {
  const path = join(DIST, og['og:image'].slice(ORIGIN.length));
  if (!existsSync(path)) {
    fail(`og:image is not in the build: ${og['og:image'].slice(ORIGIN.length)}`);
  } else {
    const bytes = readFileSync(path);
    const probe = imageSize(bytes);
    if (!probe) fail('og:image is not a readable PNG or JPEG');
    else {
      const size = probe.size;
      if (og['og:image:type'] && og['og:image:type'] !== probe.mime) {
        fail(`og:image:type declares ${og['og:image:type']} but the file is ${probe.mime}`);
      }
      const declared = [Number(og['og:image:width']), Number(og['og:image:height'])];
      if (size[0] !== declared[0] || size[1] !== declared[1]) {
        fail(
          `og:image is ${size[0]}x${size[1]} but the tags declare ${declared[0]}x${declared[1]}`,
        );
      }
      /*
       * A card renders at about 600 px wide. Under 600 the image is upscaled and
       * the wordmark goes soft; over 5 MB some crawlers give up before the
       * fetch completes and the card renders without an image at all.
       */
      if (size[0] < 600) fail(`og:image is only ${size[0]} px wide`);
      if (bytes.length > 5_000_000) fail(`og:image is ${(bytes.length / 1e6).toFixed(1)} MB`);
      notes.push(
        `og:image ${size[0]}x${size[1]} ${probe.mime}, ${(bytes.length / 1024).toFixed(0)} kB, ratio ${(
          size[0] / size[1]
        ).toFixed(2)}:1`,
      );
    }
  }
}

/*
 * The preview this one replaced must be gone, not merely unreferenced.
 *
 * `og-hangyul-ganada.jpg` was the generated preview before the canonical
 * artwork became `apps/common_assets/ob/hangyul_ganada_ob_image.png`. Social
 * platforms cache aggressively, so an old file left in the build keeps the old
 * card alive for anyone whose cache resolves it — and a tag that still names
 * it would never show the new artwork at all.
 */
const OBSOLETE_PREVIEWS = ['og-hangyul-ganada.jpg'];
for (const name of OBSOLETE_PREVIEWS) {
  if (visible.includes(name)) fail(`the retired social preview ${name} is still referenced in index.html`);
  if (existsSync(join(DIST, 'brand', name))) fail(`the retired social preview ${name} is still in the build`);
}

// --- 5. Not indexed, and readably so ---------------------------------------

for (const key of ['robots', 'googlebot']) {
  const value = (named(key) ?? '').toLowerCase();
  if (!value) fail(`no <meta name="${key}">`);
  else {
    for (const directive of NOINDEX) {
      if (!value.includes(directive)) fail(`meta ${key} is missing "${directive}"`);
    }
  }
}

/*
 * The header, in both Vercel configurations.
 *
 * There are two because the project's Root Directory setting decides which one
 * Vercel reads, and only one of them is live. Which one is not knowable from
 * here, so both have to be right — a header that exists in the inert file and
 * not in the live one is the same as no header.
 */
for (const config of ['vercel.json', join('apps', 'web', 'vercel.json')]) {
  const path = join(root, config);
  if (!existsSync(path)) continue;
  const parsed = JSON.parse(readFileSync(path, 'utf8'));
  const catchAll = (parsed.headers ?? []).find((entry) => entry.source === '/(.*)');
  const header = catchAll?.headers?.find((h) => h.key.toLowerCase() === 'x-robots-tag');
  if (!header) {
    fail(`${config} has no catch-all X-Robots-Tag header`);
  } else {
    for (const directive of NOINDEX) {
      if (!header.value.toLowerCase().includes(directive)) {
        fail(`${config} X-Robots-Tag is missing "${directive}"`);
      }
    }
  }
}

/*
 * robots.txt must not disallow, and there must be no sitemap.
 *
 * Both for the same reason: a crawler that cannot fetch the page cannot read
 * the `noindex` on it, and a sitemap is a request to index the very thing this
 * whole section is asking not to be indexed.
 */
const robotsPath = join(DIST, 'robots.txt');
if (existsSync(robotsPath)) {
  const robots = readFileSync(robotsPath, 'utf8');
  const directives = robots
    .split('\n')
    .map((line) => line.replace(/#.*/, '').trim())
    .filter(Boolean);
  for (const line of directives) {
    const disallow = /^disallow:\s*(\S.*)$/i.exec(line);
    if (disallow) {
      fail(
        `robots.txt disallows "${disallow[1]}" — a blocked page cannot be read, ` +
          'so its noindex is never seen and the URL stays listed',
      );
    }
    if (/^sitemap:/i.test(line)) fail('robots.txt advertises a sitemap');
  }
  notes.push('robots.txt allows crawling, which is what makes the noindex readable');
}

const sitemaps = readdirSync(DIST).filter((name) => /^sitemap.*\.xml$/i.test(name));
for (const name of sitemaps) fail(`${name} is in the build; this product publishes no sitemap`);

/*
 * And the thing all of the above must not have broken.
 *
 * Open Graph is read by preview crawlers, which are not search crawlers: they
 * ignore robots meta and X-Robots-Tag entirely. This assertion is not testing
 * their behaviour — it is recording that the two goals are compatible, so that
 * nobody later "fixes" the noindex by blocking crawlers and takes the preview
 * card down with it.
 */
if (!problems.length) {
  notes.push('shareable and not indexed are both satisfied, and neither disables the other');
}

// --- Report ----------------------------------------------------------------

console.log('Share metadata and indexing — the built app\n');
console.log(`  title        ${title}`);
console.log(`  description  ${description ?? '—'}`);
console.log(`  og:image     ${og['og:image'] ?? '—'}`);
console.log(`  robots       ${named('robots') ?? '—'}`);
console.log(`  googlebot    ${named('googlebot') ?? '—'}`);
console.log('');
for (const note of notes) console.log(`  ok  ${note}`);

if (problems.length) {
  console.log('');
  for (const problem of problems) console.log(`  ✗  ${problem}`);
  console.log(`\n${problems.length} problem(s).`);
  process.exit(1);
}

console.log('\n0 error(s).');

/**
 * `{ size: [w, h], mime }` read out of the file's own header, or null.
 *
 * PNG first because that is what ships; JPEG kept so the gate reports a
 * wrong-format file as a type mismatch rather than as unreadable.
 */
function imageSize(bytes) {
  // PNG: 8-byte signature, then the IHDR chunk holds width and height.
  if (
    bytes.length > 24 &&
    bytes[0] === 0x89 &&
    bytes[1] === 0x50 &&
    bytes[2] === 0x4e &&
    bytes[3] === 0x47
  ) {
    return { size: [bytes.readUInt32BE(16), bytes.readUInt32BE(20)], mime: 'image/png' };
  }
  // JPEG: walk the markers to the first SOF frame header.
  if (bytes[0] === 0xff && bytes[1] === 0xd8) {
    let offset = 2;
    while (offset < bytes.length) {
      if (bytes[offset] !== 0xff) return null;
      const marker = bytes[offset + 1];
      const length = bytes.readUInt16BE(offset + 2);
      // Any SOF except the four that are not frame headers.
      if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
        return {
          size: [bytes.readUInt16BE(offset + 7), bytes.readUInt16BE(offset + 5)],
          mime: 'image/jpeg',
        };
      }
      offset += 2 + length;
    }
  }
  return null;
}
