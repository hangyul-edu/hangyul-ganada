#!/usr/bin/env node
/**
 * The question audit, written out for a person to read.
 *
 *   node scripts/build-ambiguity-ledger.mjs           write docs/AMBIGUITY_LEDGER.md
 *   node scripts/build-ambiguity-ledger.mjs --check   fail if it is out of date
 *
 * Two halves, and the document exists because neither is sufficient alone. The
 * machine half enumerates every objective question and applies the rules that
 * can be written down; the human half is the reading, and it is the only thing
 * that can say whether a Korean sentence has one answer. This joins them: the
 * families and their counts come from the ledger the gates write, the verdicts
 * come from `content/vocabulary/ambiguity-review.json`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const CHECK = process.argv.includes('--check');
const read = (...p) => JSON.parse(readFileSync(join(ROOT, ...p), 'utf8'));

const ledger = read('content-cache', 'question-ledger.json');
const review = read('content', 'vocabulary', 'ambiguity-review.json');
const conflicts = read('content', 'vocabulary', 'answer-conflicts.json');

const families = new Map();
for (const question of ledger.questions) {
  const key = `${question.surface} ${question.type}`;
  const family = families.get(key) ?? {
    surface: question.surface,
    type: question.type,
    count: 0,
    rationale: question.rationale,
  };
  family.count += 1;
  families.set(key, family);
}

const rows = [...families.values()].sort(
  (a, b) => a.surface.localeCompare(b.surface) || b.count - a.count,
);

const lines = [];
lines.push('# The ambiguity ledger');
lines.push('');
lines.push('GENERATED by `npm run ambiguity:ledger`. Do not edit by hand — edit');
lines.push('`content/vocabulary/ambiguity-review.json` and rebuild.');
lines.push('');
lines.push('A question is acceptable only when exactly one of the choices in front of the');
lines.push('learner is correct. Checking that the stored answer id is unique does not');
lines.push('establish that, and this repository has now been caught twice believing it did.');
lines.push('This file records both halves of the check: what the gates can decide, and what');
lines.push('a person had to read.');
lines.push('');
lines.push('## 1. Every question family');
lines.push('');
lines.push(`${ledger.generated.toLocaleString('en')} objective questions, from three sources.`);
lines.push('');
lines.push('| Surface | Family | Questions | What is meant to pin the answer |');
lines.push('|:---|:---|---:|:---|');
for (const row of rows) {
  lines.push(
    `| ${row.surface} | \`${row.type}\` | ${row.count.toLocaleString('en')} | ${row.rationale} |`,
  );
}
lines.push(`| **Total** | | **${ledger.generated.toLocaleString('en')}** | |`);
lines.push('');
lines.push('## 2. What the gates decide');
lines.push('');
lines.push('| Gate | Reads | Refuses |');
lines.push('|:---|:---|:---|');
lines.push(
  '| `leveltest:ambiguity` | the shipped bank | 27 rules, including a stem that says only *when*, a predicate that rules out no noun, two people in one agent slot, and every reviewed pair |',
);
lines.push(
  '| `questions:ledger` | all three surfaces | duplicate options after NFKC, an answer that is not among the options or is there twice, an answer index that is not an index, one stem keyed two ways |',
);
lines.push('| `answerability` | all three surfaces | a question answerable without reading it |');
lines.push(
  '| `numbers:qa`, `numbers:domain` | the Numbers course | a distractor filling the same slot as the key, a counter and number that disagree |',
);
lines.push(
  '| `copy:fresh` | the 24 locale packs | an example translation whose Korean sentence has since changed |',
);
lines.push('');
lines.push('Their limit is stated rather than implied: none of them reads Korean. Every rule');
lines.push('above is a proxy for a judgement, which is why section 3 exists.');
lines.push('');
lines.push('## 3. What a person read, and what they found');
lines.push('');
lines.push(
  `Read in full: ${review.reviewed.levelTestContextItems} contextual Level Test items, ` +
    `${review.reviewed.clozeGapFills} gap-fills in the daily vocabulary queue, and ` +
    `${review.reviewed.numbersQuestions} Numbers questions — each stem composed with all four of ` +
    'its options and read as a sentence.',
);
lines.push('');
lines.push('| | Stem | Keyed | Also defensible | Verdict | Now | Held by |');
lines.push('|:---|:---|:---|:---|:---|:---|:---|');
for (const f of review.findings) {
  lines.push(
    `| ${f.id} | ${f.stem} | ${f.keyed} | ${f.rival} | **${f.verdict}** | ${f.now} | ${f.heldBy} |`,
  );
}
lines.push('');
lines.push('### Why each one was defensible');
lines.push('');
for (const f of review.findings) lines.push(`* **${f.id}** — ${f.why}.`);
lines.push('');
lines.push('## 4. The reviewed pairs');
lines.push('');
lines.push(
  `${conflicts.pairs.length} pairs of lemmas that may never be offered against each other. ` +
    'They pass every automatic guard the builder has — no shared gloss word, no shared category, ' +
    'no recorded synonym, no shared argument in their own example sentences — and still produce ' +
    'two right answers, because what they share is a selectional class nothing in the pack records.',
);
lines.push('');
lines.push('| | | Frame it was found in | Why both fit |');
lines.push('|:---|:---|:---|:---|');
for (const pair of conflicts.pairs) {
  lines.push(`| ${pair.a} | ${pair.b} | ${pair.frame} | ${pair.why} |`);
}
lines.push('');
lines.push('## 5. What this ledger does not cover');
lines.push('');
lines.push(`* ${review.notFound.levelTestMeaningItems}`);
lines.push('* Whether a translated choice reads naturally to a native speaker of that language.');
lines.push('  The 24 locale packs are machine-assisted and unreviewed; `docs/report.md` carries');
lines.push('  that blocker and this file does not close it.');
lines.push('* Whether audio introduces a second reading. The listening questions were read as');
lines.push('  text and their clips were checked for existence and duration, not listened to.');
lines.push('');

const text = `${lines.join('\n')}\n`;
const out = join(ROOT, 'docs', 'AMBIGUITY_LEDGER.md');
if (CHECK) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {
    /* falls through to the mismatch below */
  }
  if (current !== text) {
    console.error('docs/AMBIGUITY_LEDGER.md is out of date — run `npm run ambiguity:ledger`');
    process.exit(1);
  }
  console.log(
    `ambiguity ledger current — ${rows.length} families, ${review.findings.length} reviewed findings`,
  );
  process.exit(0);
}
writeFileSync(out, text);
console.log(
  `wrote docs/AMBIGUITY_LEDGER.md — ${rows.length} families, ${review.findings.length} reviewed findings`,
);
