#!/usr/bin/env node
/**
 * Renders docs/TRANSLATION_QUALITY_MATRIX.md — per-locale content status,
 * derived from the tree plus the pipeline's adjudication records in
 * content/vocabulary/translation-adjudication.json (written by the paydown
 * pipeline; {locale: {reviewed, rewrites, findingsByRule}}).
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(ROOT, p), 'utf8'));
const v = read('apps/web/src/data/generated/vocabulary.json');
const total = v.words.length;
const style = read('content/vocabulary/locale-style.json').locales;
const adj = existsSync(join(ROOT, 'content/vocabulary/translation-adjudication.json'))
  ? read('content/vocabulary/translation-adjudication.json') : {};
const iface = {};
for (const loc of Object.keys(style)) {
  const dir = join(ROOT, `apps/web/src/locales/${loc}`);
  iface[loc] = existsSync(dir) ? readdirSync(dir).length : 0;
}
let out = `# Translation quality matrix\n\nGenerated by \`scripts/build-translation-quality-matrix.mjs\`. Coverage is
measured from the tree; review numbers come from the pipeline's adjudication
ledger. **Native-reviewed is 0 for every locale** — nothing here claims
otherwise; content reaches at most MODEL-EDITORIALLY-REVIEWED.\n\n`;
out += `| locale | interface bundles | meanings | example translations | notes | untranslated | adjudicated rewrites | status |\n| --- | --- | --- | --- | --- | --- | --- | --- |\n`;
for (const loc of Object.keys(style).sort()) {
  if (loc === 'ko') continue;
  let meanings = 0, exs = 0, notes = 0;
  const copyPath = `content/vocabulary/copy/${loc}.json`;
  if (existsSync(join(ROOT, copyPath))) {
    for (const r of Object.values(read(copyPath).words)) {
      if (r && r[0]) meanings += 1;
      if (r && r[1]) exs += 1;
      if (r && r[2]) notes += 1;
    }
  } else if (existsSync(join(ROOT, `apps/web/src/data/generated/vocabulary.${loc}.json`))) {
    const pack = read(`apps/web/src/data/generated/vocabulary.${loc}.json`).words;
    for (const r of pack) { if (r && r[0]) meanings += 1; if (r && r[1]) exs += 1; if (r && r[2]) notes += 1; }
  }
  const a = adj[loc] ?? {};
  const status = meanings >= total
    ? (a.reviewed ? 'MODEL-EDITORIALLY-REVIEWED' : 'GENERATED')
    : `PARTIAL (${meanings}/${total})`;
  out += `| ${loc} | ${iface[loc]} | ${meanings} | ${exs} | ${notes} | ${total - meanings} | ${a.rewrites ?? '—'} | ${status} |\n`;
}
out += `\nSemantic-feature findings and exceptions: \`npm run translation:semantics\` and
\`content/vocabulary/semantics-exceptions.json\`. Register policy per locale:
\`content/vocabulary/locale-style.json\`. Duplicate/collapsed translations:
\`npm run vocabulary:translation:check\` and its shared-translations ledger.\n`;
writeFileSync(join(ROOT, 'docs/TRANSLATION_QUALITY_MATRIX.md'), out);
console.log('wrote docs/TRANSLATION_QUALITY_MATRIX.md');
