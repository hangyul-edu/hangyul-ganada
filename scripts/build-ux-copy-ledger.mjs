#!/usr/bin/env node
/**
 * docs/UX_COPY_REMEDIATION_LEDGER.md, from docs/ux-copy-remediation.json.
 *
 *   npm run copy:remediation            write the document
 *   npm run copy:remediation:check      fail if it is stale, or if a row's
 *                                       "new" text is not what the bundle
 *                                       actually carries now
 *
 * One row per string per locale that this pass changed, added or removed,
 * with the columns the release requires: key, source path, old text, new
 * text, reason, the metric or behaviour the string represents, the locales
 * affected, and how the change was verified. The "new" column is checked
 * against the live bundle, so the ledger cannot describe a wording that was
 * later changed back.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const CHECK = process.argv.includes('--check');
const SOURCE = join(root, 'docs/ux-copy-remediation.json');
const OUT = join(root, 'docs/UX_COPY_REMEDIATION_LEDGER.md');

const data = JSON.parse(readFileSync(SOURCE, 'utf8'));
const problems = [];
const cell = (v) => (v === null || v === undefined ? '—' : String(v).replace(/\|/g, '\\|').replace(/\n/g, ' '));

function live(row) {
  if (!row.path.endsWith('.json')) return undefined;
  const bundle = JSON.parse(readFileSync(join(root, row.path), 'utf8'));
  const path = row.key.split(':')[1].split('.');
  let node = bundle;
  for (const part of path) {
    if (!node || typeof node !== 'object' || !(part in node)) return null;
    node = node[part];
  }
  return node;
}

for (const row of data.rows) {
  const now = live(row);
  if (now === undefined) continue;
  if (row.kind === 'removed' ? now !== null : now !== row.new) {
    problems.push(`${row.key} [${row.locale}]: the ledger says ${JSON.stringify(row.new)} but the bundle carries ${JSON.stringify(now)}`);
  }
}

/** Rows grouped by key so a 32-locale change is one entry with 32 sub-rows. */
const byKey = new Map();
for (const row of data.rows) {
  if (!byKey.has(row.key)) byKey.set(row.key, []);
  byKey.get(row.key).push(row);
}

const counts = { rewritten: 0, added: 0, removed: 0 };
for (const row of data.rows) counts[row.kind] = (counts[row.kind] ?? 0) + 1;

const sections = [...byKey.entries()].map(([key, rows]) => {
  const first = rows[0];
  const locales = rows.map((r) => r.locale);
  const head = `### \`${key}\` — ${first.kind}\n\n| Field | Value |\n| --- | --- |\n| String key or content ID | \`${key}\` |\n| Source path | ${rows.length === 1 ? `\`${first.path}\`` : `\`${first.path.replace(`/${first.locale}/`, '/<locale>/')}\``} |\n| Reason | ${cell(first.reason)} |\n| Metric or behavior represented | ${cell(first.metric)} |\n| Locales affected | ${locales.length} — ${locales.map((l) => `\`${l}\``).join(', ')} |\n| Verification result | ${cell(first.verification)} |\n`;
  const table = `\n| Locale | Old text | New text |\n| --- | --- | --- |\n${rows.map((r) => `| \`${r.locale}\` | ${cell(r.old)} | ${cell(r.new)} |`).join('\n')}\n`;
  return head + table;
});

const md = `# UX copy remediation ledger

Generated by \`scripts/build-ux-copy-ledger.mjs\` from \`docs/ux-copy-remediation.json\`.
Do not edit by hand; \`npm run copy:remediation:check\` fails when this file is
stale or when a row's *new text* is no longer what the bundle carries.

Base commit for the *old text* column: \`${data.baseCommit}\`. The audit that
produced these rows is \`docs/UX_COPY_AUDIT.md\`; the rules they were held to are
\`docs/UX_COPY_STYLE_GUIDE.md\`.

**${data.rows.length} rows** — ${counts.rewritten} rewritten, ${counts.added} added, ${counts.removed} removed — across ${byKey.size} keys.

Each entry lists the key, the source path, the reason, the metric or behaviour
the string represents, the locales affected and the verification, followed by
the old and new text per locale.

${sections.join('\n')}`;

if (CHECK) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== md) problems.push(`${OUT.slice(root.length + 1)} is stale — run npm run copy:remediation`);
} else {
  writeFileSync(OUT, md);
}

console.log(`UX copy remediation ledger — ${data.rows.length} rows over ${byKey.size} keys (${counts.rewritten} rewritten · ${counts.added} added · ${counts.removed} removed)`);
if (problems.length) {
  console.error(`\n${problems.length} problem(s):`);
  for (const p of problems.slice(0, 40)) console.error(`  ! ${p}`);
  process.exit(CHECK ? 1 : 0);
}
console.log(CHECK ? '  document is current and every new text is what the bundle carries.' : `  wrote ${OUT.slice(root.length + 1)}`);
