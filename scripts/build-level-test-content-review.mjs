#!/usr/bin/env node
/**
 * Every sentence a learner can meet before they have proved anything, written out.
 *
 *   node scripts/build-level-test-content-review.mjs           write the document
 *   node scripts/build-level-test-content-review.mjs --check   fail if it is stale
 *
 * ## Why this document and not another gate
 *
 * `leveltest:policy` decides mechanical questions — is this level justified by
 * this sentence, does this band contain a connective, can this history reach
 * this item. None of them is *does a Korean speaker think this question has one
 * answer*, and no rule in this repository reads Korean.
 *
 * The reported defect was found by a person looking at a screen. So the items a
 * beginner can actually reach are printed here in full, with the demand that put
 * them where they are, small enough that reading all of them is an afternoon
 * rather than a project. `content/vocabulary/ambiguity-review.json` carries the
 * verdicts from the last reading.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { BANDS, bandOf } from '../apps/web/src/domain/levelTest.ts';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const CHECK = process.argv.includes('--check');
const read = (...p) => JSON.parse(readFileSync(join(ROOT, ...p), 'utf8'));

const manifest = read('apps', 'web', 'public', 'level-test', 'manifest.json');
const bank = read('apps', 'web', 'public', 'level-test', manifest.bank);
const conflicts = read('content', 'vocabulary', 'answer-conflicts.json');
const review = read('content', 'vocabulary', 'ambiguity-review.json');

const contexts = bank.items.filter((item) => item.kind === 'context');
const perBand = new Map();
for (const item of contexts) {
  const band = bandOf(item.level);
  if (!perBand.has(band)) perBand.set(band, []);
  perBand.get(band).push(item);
}
const sorted = (band) =>
  [...(perBand.get(band) ?? [])].sort((a, b) => a.level - b.level || a.prompt.localeCompare(b.prompt));

const BAND_NAMES = [
  'foundation',
  'elementary',
  'lower intermediate',
  'intermediate',
  'upper intermediate',
  'advanced',
];

const lines = [];
lines.push('# Level test — content review');
lines.push('');
lines.push('GENERATED by `npm run leveltest:content`. Do not edit by hand.');
lines.push('');
lines.push(
  `${contexts.length.toLocaleString('en')} contextual items in the shipped bank. ` +
    'The two lowest bands are printed in full because they are what a learner meets ' +
    'before they have demonstrated anything, and because the defect that produced this ' +
    'document was in one of them.',
);
lines.push('');
lines.push('## How many, and where');
lines.push('');
lines.push('| Band | Levels | Name | Sentences |');
lines.push('|---:|:---|:---|---:|');
for (const [at, [floor, top]] of BANDS.entries()) {
  lines.push(`| ${at + 1} | ${floor}–${top} | ${BAND_NAMES[at]} | ${(perBand.get(at) ?? []).length} |`);
}
lines.push('');

for (const band of [0, 1]) {
  lines.push(`## Band ${band + 1} — ${BAND_NAMES[band]}, levels ${BANDS[band][0]}–${BANDS[band][1]}`);
  lines.push('');
  lines.push('| Level | Sentence | Options | Answer | Grammar | Hardest word | Eojeol |');
  lines.push('|---:|:---|:---|:---|:---|:---|---:|');
  for (const item of sorted(band)) {
    const demand = item.demand ?? {};
    lines.push(
      `| ${item.level} | ${item.prompt} | ${item.options.join(' · ')} | ${item.answer} | ` +
        `${(demand.grammar ?? []).join(', ') || '—'} | ` +
        `${demand.hardest ?? '—'} L${demand.noun ?? 0} | ${demand.eojeol ?? '—'} |`,
    );
  }
  lines.push('');
}

lines.push('## What was read, and what it found');
lines.push('');
lines.push(
  `Every contextual item and every gap-fill in the daily queue was read. ` +
    `${review.findings.length} items had a second defensible answer; each is recorded in ` +
    '`docs/AMBIGUITY_LEDGER.md` with the sentence, both readings, the verdict and what holds ' +
    'it closed.',
);
lines.push('');
lines.push('## The reviewed pairs');
lines.push('');
lines.push(
  `${conflicts.pairs.length} pairs of words that may never be offered against each other. They ` +
    'pass every automatic guard the builder has and still make two right answers, because what ' +
    'they share is a selectional class nothing in the corpus records.',
);
lines.push('');
lines.push('| | | Found in |');
lines.push('|:---|:---|:---|');
for (const pair of conflicts.pairs) lines.push(`| ${pair.a} | ${pair.b} | ${pair.frame} |`);
lines.push('');
lines.push('## What this review does not establish');
lines.push('');
lines.push('* **That a Korean speaker agrees.** No locale, Korean included, has been read by a');
lines.push('  qualified native speaker. Every rule in every gate is structural and structural is a');
lines.push('  proxy for a judgement.');
lines.push('* **That the levels mean anything to a learner.** The scale is curriculum-based and');
lines.push('  uncalibrated — see `docs/LEVEL_TEST_DIFFICULTY_AUDIT.md` §5.');
lines.push('* **That the next build looks like this one.** The bank is regenerated with a different');
lines.push('  distractor draw whenever the corpus moves. The rules and the reviewed pairs carry');
lines.push('  forward; this reading does not.');
lines.push('');

const text = `${lines.join('\n')}\n`;
const out = join(ROOT, 'docs', 'LEVEL_TEST_CONTENT_REVIEW.md');
if (CHECK) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {
    /* falls through */
  }
  if (current !== text) {
    console.error('docs/LEVEL_TEST_CONTENT_REVIEW.md is out of date — run `npm run leveltest:content`');
    process.exit(1);
  }
  console.log(
    `level test content review current — ${contexts.length} items, ` +
      `${(perBand.get(0) ?? []).length} in the foundation band`,
  );
  process.exit(0);
}
writeFileSync(out, text);
console.log(`wrote docs/LEVEL_TEST_CONTENT_REVIEW.md — ${contexts.length} contextual items`);
