#!/usr/bin/env node
/**
 * docs/QUOTE_TRANSLATION_REVIEW_v1.0.5.md — the v1.0.5 review of the two
 * home-screen quotations, 64 rows, generated from the same three inputs as
 * docs/QUOTE_TRANSLATION_AUDIT.md so the two can never disagree.
 *
 *   node scripts/build-quote-review-v105.mjs           write
 *   node scripts/build-quote-review-v105.mjs --check   fail when stale
 *
 * What this document adds over the audit: one row per (quotation, locale)
 * with the exact shipped strings, the review label in the v1.0.5 vocabulary
 * (AUTOMATED CHECKED / MODEL-REVIEWED / HUMAN REVIEW REQUIRED — never
 * NATIVE-SPEAKER REVIEWED, because none has happened), the rendering result,
 * and the attribution facts for the Carlyle line stated plainly.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const CHECK = process.argv.includes('--check');
const OUT = join(root, 'docs/QUOTE_TRANSLATION_REVIEW_v1.0.5.md');

const quotes = await import('../apps/web/src/data/quotes.ts');
const { LEARNING_QUOTES: ALL_QUOTES, QUOTE_LOCALES, renderQuote } = quotes;
const J = JSON.parse(readFileSync(join(root, 'docs/quote-translation-audit.json'), 'utf8'));
const R = JSON.parse(readFileSync(join(root, 'docs/quote-render-audit.json'), 'utf8'));
/** The two home-screen rows the audit judges; the twenty attributed library rows are covered by quotes:qa and the audit's own scope. */
const LEARNING_QUOTES = ALL_QUOTES.filter((q) => q.id in J.quotes);

const cell = (t) => String(t ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ').trim();
const label = (status) => ({
  'PASS': 'MODEL-REVIEWED',
  'CORRECTED AND PASS': 'MODEL-REVIEWED (corrected)',
  'NATIVE-SPEAKER REVIEW REQUIRED': 'MODEL-REVIEWED; HUMAN REVIEW REQUIRED',
  'BLOCKED': 'OPEN',
}[status] ?? status);

const L = [];
L.push('# Quotation translation review — web v1.0.5');
L.push('');
L.push('GENERATED by `scripts/build-quote-review-v105.mjs` from `apps/web/src/data/quotes.ts`, `docs/quote-translation-audit.json` (the reviewer\'s judgments, dated ' + J.reviewed + ') and `docs/quote-render-audit.json` (rendered ' + (R.renderedAt ?? 'unknown') + '). Do not edit the tables by hand. The fuller per-row grammar and punctuation notes are in `docs/QUOTE_TRANSLATION_AUDIT.md`; this document is the v1.0.5 evidence view: 64 rows, one label each, and the attribution facts.');
L.push('');
L.push('## Labels used here');
L.push('');
L.push('| Label | Meaning |');
L.push('|:---|:---|');
L.push('| MODEL-REVIEWED | The model that wrote the translation read it again for meaning, metaphor, tone, grammar and punctuation. |');
L.push('| MODEL-REVIEWED (corrected) | The same reading changed the string; the correction is recorded in the audit. |');
L.push('| MODEL-REVIEWED; HUMAN REVIEW REQUIRED | The reading passed, and names a point only a native speaker can settle. |');
L.push('| NATIVE-SPEAKER REVIEWED | **Used for no row.** No native speaker has read these lines. |');
L.push('| OPEN | The row is clipped in the render audit or has no review; none in this build unless the totals say so. |');
L.push('');
L.push('## Attribution facts');
L.push('');
for (const q of LEARNING_QUOTES) {
  const auth = q.authorship === 'unknown' ? 'author unknown, shipped as 작자 미상 in every locale' : `named author; sourceStatus = ${q.sourceStatus ?? 'confirmed'}`;
  L.push(`* **${q.id}** — ${cell(q.originalText)} — ${auth}. Source note: ${cell(q.source)}`);
}
L.push('');
L.push('The Carlyle line is shown under Carlyle\'s name because that is the attribution the product owner asked for and the one every quotation collection gives it; the runtime `source` field and the audit both say it has **not** been located in his published works. The app does not claim otherwise anywhere a learner can see, and `scripts/quotes-qa.mjs` only lets a row hedge when it carries `sourceStatus: "attributed"`.');
L.push('');

let counts = {};
const finals = {};
/** The 14-column row the v1.0.5 evidence asks for; one per (quotation, locale). */
const native = (j) => (j.status === 'NATIVE-SPEAKER REVIEW REQUIRED' || /native/i.test(j.review ?? '') ? 'HUMAN REVIEW REQUIRED' : 'not performed');
const finalOf = (j, ok) => (!ok ? 'OPEN' : j.status === 'BLOCKED' ? 'OPEN' : j.status === 'NATIVE-SPEAKER REVIEW REQUIRED' ? 'HUMAN REVIEW REQUIRED' : 'RESOLVED');
L.push('## Review table (64 rows)');
L.push('');
L.push('Columns: Quote ID, Locale, Korean source, Translation, Displayed attribution, Meaning preserved, Metaphor preserved, Naturalness, Register, Punctuation, Model-review status, Native-review status, Required correction, Final status. "Meaning", "Metaphor", "Naturalness" and "Register" were judged row by row against the Korean source on ' + (J.columnsReviewed ?? J.reviewed) + ' by the model; "Native-review status" is HUMAN REVIEW REQUIRED wherever the reading names a point only a native speaker can settle, and *not performed* otherwise — no row is NATIVE-SPEAKER REVIEWED. "Required correction" records the change already made to the shipped string (or none). "Final status" uses the ledger vocabulary: RESOLVED when the row passed and needs no native check, HUMAN REVIEW REQUIRED when it does, OPEN when it is clipped or unreviewed.');
L.push('');
L.push('| Quote ID | Locale | Korean source | Translation | Displayed attribution | Meaning preserved | Metaphor preserved | Naturalness | Register | Punctuation | Model-review status | Native-review status | Required correction | Final status |');
L.push('|:---|:---|:---|:---|:---|:---|:---|:---|:---|:---|:---|:---|:---|:---|');
for (const q of LEARNING_QUOTES) {
  for (const loc of QUOTE_LOCALES) {
    const r = renderQuote(q, loc);
    const j = J.quotes[q.id]?.[loc] ?? {};
    const render = R.results?.[loc]?.[q.id];
    const ok = render ? Object.values(render.widths).every((x) => x.ok) : false;
    const fin = finalOf(j, ok);
    finals[fin] = (finals[fin] ?? 0) + 1;
    const model = j.status ? (j.status === 'BLOCKED' ? 'OPEN' : 'MODEL-REVIEWED' + (j.status === 'CORRECTED AND PASS' ? ' (corrected)' : '')) : 'NOT REVIEWED';
    const corr = j.correction && j.correction !== '—' ? j.correction : 'none';
    L.push(`| ${q.id} | ${loc} | ${cell(q.originalText)} | ${cell(r.text)} | ${cell(r.author)} | ${cell(j.meaning ?? 'NOT JUDGED')} | ${cell(j.metaphor ?? 'NOT JUDGED')} | ${cell(j.naturalness ?? 'NOT JUDGED')} | ${cell(j.register ?? 'NOT JUDGED')} | ${cell(j.punct ?? '—')} | ${model} | ${native(j)} | ${cell(corr)} | ${fin} |`);
  }
}
L.push('');
L.push('| Final status | Rows |');
L.push('|:---|---:|');
for (const [k, v] of Object.entries(finals)) L.push(`| ${k} | ${v} |`);
L.push('');
L.push('Metaphor note: the Carlyle line names the stone twice — 걸림돌 (a stone one trips on) and 디딤돌 (a stone one steps on). Where a language has no everyday stone idiom for both, the translation keeps the weak/strong contrast with *obstacle* / *step* and the row says PARTIALLY PRESERVED; that is a translation decision, not a defect, and it is listed so a native reviewer can offer a stone idiom where one exists.');
L.push('');
for (const q of LEARNING_QUOTES) {
  L.push(`## ${q.id} — label and rendering`);
  L.push('');
  L.push(`Korean: ${cell(q.originalText)}`);
  L.push('');
  L.push('| # | Locale | Shipped quotation | Shipped byline | Label | Rendering | Remaining human check |');
  L.push('|---:|:---|:---|:---|:---|:---|:---|');
  let n = 0;
  for (const loc of QUOTE_LOCALES) {
    n += 1;
    const r = renderQuote(q, loc);
    const j = J.quotes[q.id]?.[loc] ?? {};
    const render = R.results?.[loc]?.[q.id];
    const ok = render ? Object.values(render.widths).every((x) => x.ok) : false;
    const rendering = render ? (ok ? `wraps at ${R.widths.join('/')}, ${(R.scales ?? [1, 2]).map((s) => s * 100).join('/')} %` : 'CLIPPED') : 'NOT RENDERED';
    const lab = label(j.status ?? 'BLOCKED');
    counts[lab] = (counts[lab] ?? 0) + 1;
    L.push(`| ${n} | ${loc} | ${cell(r.text)} | ${cell(r.author)} | ${lab} | ${rendering} | ${cell(j.review ?? '—')} |`);
  }
  L.push('');
}
L.push('## Totals');
L.push('');
L.push('| Label | Rows |');
L.push('|:---|---:|');
for (const [k, v] of Object.entries(counts)) L.push(`| ${k} | ${v} |`);
L.push(`| Total | ${Object.values(counts).reduce((a, b) => a + b, 0)} |`);
L.push('');
L.push('Gates: `npm run quotes:qa:check`, `npm run quotes:audit:check`, `npm run quotes:render:check`. Their exit codes for this build are recorded in `docs/WEB_CONTENT_QA_EVIDENCE_v1.0.5.md`.');
L.push('');
const md = L.join('\n');
if (CHECK) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== md) { console.error(`${OUT} is stale — run node scripts/build-quote-review-v105.mjs`); process.exit(1); }
  console.log('quote review current');
} else {
  writeFileSync(OUT, md);
  console.log(`wrote ${OUT}: ${Object.values(counts).reduce((a, b) => a + b, 0)} rows`);
}
