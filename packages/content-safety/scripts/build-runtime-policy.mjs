#!/usr/bin/env node
/**
 * The runtime policy: the full policy, cut down to what the app can afford to
 * carry.
 *
 *   node packages/content-safety/scripts/build-runtime-policy.mjs
 *   node packages/content-safety/scripts/build-runtime-policy.mjs --check
 *
 * The full policy carries surface forms in thirty-two languages and the
 * English gloss indicators the dictionary and assessment builders read; that
 * is 370 kB, most of it for languages whose strings are validated at
 * publication and never generated at runtime. The runtime gate revalidates
 * *Korean* content — the bank, the gap-fills, a legacy sitting, a cached plan,
 * a distractor chosen in the browser — plus the romanised forms that travel
 * with it; a dictionary anchor's headword is in its id, so an item is refused
 * from the Korean in every interface language. So this writes the same policy
 * minus the thirty-one other languages and the gloss indicators, keeps the
 * version, and the check form fails if the committed file lags the source.
 * The whole thing has to fit a 24 kB route-chunk budget with the evaluator.
 *
 * ## The other thirty-one languages, and English
 *
 * Until v1.0.5 the runtime carried no English lists — they would have put the
 * chunk past its budget — so a Latin term hidden in a Korean field, which the
 * release scanner refuses by reading the English lists for any Latin text, was
 * the publication gate's alone; and a meaning shown in the learner's own
 * language was never re-read on the device at all. Neither limit is accepted
 * now. Every language's lists are written to `policy/runtime/<lang>.json` as a
 * *supplement* — that language's surfaces, match modes, exceptions and
 * context rules, and nothing else — and `runtime.ts` loads the learner's own
 * supplement plus English on demand, merging them into the base policy. Each
 * supplement is its own chunk, small, fetched once, and the route budget is
 * measured on every one of them rather than raised.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const SOURCE = join(HERE, 'policy', 'child-safe-content-policy.json');
const TARGET = join(HERE, 'policy', 'runtime-policy.json');
const CHECK = process.argv.includes('--check');
const KEEP = new Set(['ko', '*']);

const full = JSON.parse(readFileSync(SOURCE, 'utf8'));
const pick = (byLang) =>
  Object.fromEntries(Object.entries(byLang ?? {}).filter(([lang]) => KEEP.has(lang)));

const runtime = {
  $comment:
    'GENERATED by packages/content-safety/scripts/build-runtime-policy.mjs from child-safe-content-policy.json — Korean, English and romanised forms only, for the runtime delivery gate. Do not edit; edit the full policy and rebuild.',
  version: full.version,
  severities: full.severities,
  categories: full.categories,
  languageDefaults: full.languageDefaults,
  latinScript: full.latinScript,
  koreanParticles: full.koreanParticles,
  leet: full.leet,
  concepts: full.concepts.map((concept) => ({
    id: concept.id,
    category: concept.category,
    severity: concept.severity,
    surfaces: pick(concept.surfaces),
    romanized: concept.romanized ?? [],
    match: pick(concept.match),
    exceptions: pick(concept.exceptions),
    allow: concept.allow,
    guidance: '',
  })),
  contextRules: full.contextRules,
  glossIndicators: {},
  allow: { exact: full.allow.exact, headwords: full.allow.headwords, senseIds: full.allow.senseIds },
};

/*
 * The retired-word ids, and only the ids.
 *
 * The runtime needs to know *that* a word is retired, never why: the ledger's
 * reasons quote the sentences that were retired, and shipping them would put
 * the retired sentences back into the bundle. So the app imports this file
 * and the ledger stays in `content/`.
 */
const LEDGER = join(HERE, '..', '..', 'content', 'vocabulary', 'retired-words.json');
const IDS = join(HERE, 'policy', 'retired-word-ids.json');
const ledger = JSON.parse(readFileSync(LEDGER, 'utf8'));
const ids = {
  $comment: 'GENERATED by build-runtime-policy.mjs from content/vocabulary/retired-words.json — the ids only. Do not edit.',
  policyVersion: ledger.policyVersion,
  ids: Object.keys(ledger.words).sort(),
};
const renderedIds = `${JSON.stringify(ids)}\n`;

/*
 * The per-language supplements.
 *
 * One file per language the full policy names anywhere — a surface list, a
 * match mode, an exception or a context rule. The shape mirrors the base
 * policy's concept list so the runtime can merge by concept id; a language
 * with nothing to say about a concept gets no entry for it.
 */
const SUPPLEMENT_DIR = join(HERE, 'policy', 'runtime');
const languages = new Set();
for (const concept of full.concepts) {
  for (const table of [concept.surfaces, concept.match, concept.exceptions]) {
    for (const lang of Object.keys(table ?? {})) if (!KEEP.has(lang)) languages.add(lang);
  }
}
for (const rule of full.contextRules) if (!KEEP.has(rule.lang)) languages.add(rule.lang);
const supplementLanguages = [...languages].sort();
const supplements = new Map();
for (const lang of supplementLanguages) {
  const only = (table) => (table && table[lang] !== undefined ? { [lang]: table[lang] } : {});
  supplements.set(lang, {
    $comment: `GENERATED by build-runtime-policy.mjs from child-safe-content-policy.json — the ${lang} lists only, merged into runtime-policy.json on the device when ${lang} is the interface language. Do not edit.`,
    version: full.version,
    lang,
    concepts: full.concepts
      .map((concept) => ({
        id: concept.id,
        surfaces: only(concept.surfaces),
        match: only(concept.match),
        exceptions: only(concept.exceptions),
      }))
      .filter((c) => Object.keys(c.surfaces).length || Object.keys(c.match).length || Object.keys(c.exceptions).length),
    contextRules: full.contextRules.filter((rule) => rule.lang === lang),
    // The gloss indicators are English by definition: they classify an
    // English gloss whatever its Korean surface. They travel with English.
    ...(lang === 'en' ? { glossIndicators: full.glossIndicators } : {}),
  });
}
const INDEX = join(SUPPLEMENT_DIR, 'index.json');
const renderedIndex = `${JSON.stringify({
  $comment: 'GENERATED by build-runtime-policy.mjs — the languages a runtime supplement exists for. Do not edit.',
  version: full.version,
  languages: supplementLanguages,
})}\n`;

const rendered = `${JSON.stringify(runtime)}\n`;
let current = '';
try {
  current = readFileSync(TARGET, 'utf8');
} catch {
  current = '';
}
let currentIds = '';
try {
  currentIds = readFileSync(IDS, 'utf8');
} catch {
  currentIds = '';
}
const readOr = (path) => {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return '';
  }
};
const supplementsStale = [];
for (const [lang, doc] of supplements) {
  if (readOr(join(SUPPLEMENT_DIR, `${lang}.json`)) !== `${JSON.stringify(doc)}\n`) supplementsStale.push(lang);
}
if (readOr(INDEX) !== renderedIndex) supplementsStale.push('index');
if (existsSync(SUPPLEMENT_DIR)) {
  for (const name of readdirSync(SUPPLEMENT_DIR)) {
    const lang = name.replace(/\.json$/, '');
    if (name !== 'index.json' && !supplements.has(lang)) supplementsStale.push(`${lang} (no longer in the policy)`);
  }
}

if (CHECK) {
  if (current !== rendered || currentIds !== renderedIds) {
    console.error('runtime-policy.json or retired-word-ids.json is stale — run `npm run policy:runtime`');
    process.exit(1);
  }
  if (supplementsStale.length) {
    console.error(`policy/runtime/ is stale (${supplementsStale.join(', ')}) — run \`npm run policy:runtime\``);
    process.exit(1);
  }
  console.log(
    `runtime-policy.json is current (${(rendered.length / 1024).toFixed(0)} kB, policy ${full.version}); ${supplements.size} language supplements current`,
  );
} else {
  writeFileSync(TARGET, rendered);
  writeFileSync(IDS, renderedIds);
  mkdirSync(SUPPLEMENT_DIR, { recursive: true });
  for (const name of existsSync(SUPPLEMENT_DIR) ? readdirSync(SUPPLEMENT_DIR) : []) {
    const lang = name.replace(/\.json$/, '');
    if (name !== 'index.json' && !supplements.has(lang)) unlinkSync(join(SUPPLEMENT_DIR, name));
  }
  let largest = 0;
  for (const [lang, doc] of supplements) {
    const text = `${JSON.stringify(doc)}\n`;
    largest = Math.max(largest, text.length);
    writeFileSync(join(SUPPLEMENT_DIR, `${lang}.json`), text);
  }
  writeFileSync(INDEX, renderedIndex);
  console.log(
    `wrote runtime-policy.json (${(rendered.length / 1024).toFixed(0)} kB, policy ${full.version}), retired-word-ids.json (${ids.ids.length} ids) and ${supplements.size} language supplements (largest ${(largest / 1024).toFixed(0)} kB)`,
  );
}
